def test_dates() -> None:
    now = "SYS_EXTRACT_UTC(SYSTIMESTAMP)"
    assert (
        sql("SELECT datetime('now') FROM t")
        == f"SELECT TO_CHAR({now}, 'YYYY-MM-DD HH24:MI:SS') FROM t"
    )
    assert sql("SELECT datetime('now', '-7 days') FROM t") == (
        f"SELECT TO_CHAR(({now} + NUMTODSINTERVAL(-7, 'DAY')), 'YYYY-MM-DD HH24:MI:SS') FROM t"
    )
    assert sql("SELECT a FROM t WHERE datetime(t.at) <= ?") == (
        "SELECT a FROM t WHERE SUBSTR(REPLACE(t.at, 'T', ' '), 1, 19) <= :b0"
    )
    assert sql("SELECT date(?) FROM t") == "SELECT SUBSTR(REPLACE(:b0, 'T', ' '), 1, 10) FROM t"
    assert sql("SELECT strftime('%Y-%m-%dT%H:%M:%SZ', 'now') FROM t") == (
        f'SELECT TO_CHAR({now}, \'YYYY"-"MM"-"DD"T"HH24":"MI":"SS"Z"\') FROM t'
    )
    with pytest.raises(DialectError):
        translate("SELECT datetime('now', ?) FROM t")


def test_functions_and_conditions() -> None:
    assert sql("SELECT group_concat(name, ', '), max(a, b), max(c) FROM t") == (
        "SELECT LISTAGG(name, ', ') WITHIN GROUP (ORDER BY NULL), GREATEST(a, b), MAX(c) FROM t"
    )
    assert sql("SELECT IFNULL(a, 0), CAST(id AS TEXT) FROM t WHERE 1") == (
        "SELECT COALESCE(a, 0), CAST(id AS VARCHAR2(4000)) FROM t WHERE 1 = 1"
    )
    assert sql(
        "SELECT id FROM t WHERE name = ? COLLATE NOCASE AND id IS NOT ? ORDER BY name COLLATE"
        " NOCASE"
    ) == (
        "SELECT id FROM t WHERE LOWER(name) = LOWER(:b0) AND DECODE(id, :b1, 1, 0) = 0 ORDER BY"
        " LOWER(name)"
    )
    assert sql("UPDATE t SET data = X'00ff', other = X'' WHERE flag = TRUE") == (
        "UPDATE t SET data = HEXTORAW('00ff'), other = EMPTY_BLOB() WHERE flag = 1"
    )


def test_select_without_from_reads_dual() -> None:
    assert sql("SELECT 1") == "SELECT 1 FROM DUAL"
    assert sql("SELECT ? AS a WHERE ? = 1") == "SELECT :b0 AS a FROM DUAL WHERE :b1 = 1"
    assert (
        sql("SELECT a FROM t WHERE EXISTS (SELECT 1 FROM u)")
        == "SELECT a FROM t WHERE EXISTS (SELECT 1 FROM u)"
    )


def test_reserved_names_and_aliases() -> None:
    assert sql(
        "SELECT m.trigger, level FROM run_metadata AS m JOIN (SELECT 1 AS x FROM t) AS j ON 1 = 1"
    ) == ('SELECT m."TRIGGER", "LEVEL" FROM run_metadata m JOIN (SELECT 1 AS x FROM t) j ON 1 = 1')
    assert sql('SELECT "name" FROM "users"') == 'SELECT "NAME" FROM "USERS"'


def test_a_clob_is_compared_through_dbms_lob() -> None:
    assert sql("SELECT 1 FROM notes WHERE id = ? AND body = ?", Catalog()) == (
        "SELECT 1 FROM notes WHERE id = :b0 AND DBMS_LOB.COMPARE(body, TO_CLOB(:b1)) = 0"
    )
    # Setting a CLOB is not comparing one.
    assert (
        sql("UPDATE notes SET body = ? WHERE id = ?", Catalog())
        == "UPDATE notes SET body = :b0 WHERE id = :b1"
    )


def test_the_schema_is_read_from_oracle_views() -> None:
    text = sql("SELECT name FROM sqlite_master WHERE type = 'table'")
    assert "FROM all_tables" in text and "sqlite_master WHERE type = 'table'" in text
    info = translate("PRAGMA table_info(users)").render(None)[0]
    assert "all_tab_columns" in info and "c.table_name = 'USERS'" in info
    assert "all_indexes" in translate("PRAGMA index_list(schedules)").render(None)[0]
    assert translate("PRAGMA journal_mode = WAL").noop
    assert translate("VACUUM").noop


def test_tables_and_outer_joins_are_known_for_reading_blank_text() -> None:
    statement = translate("SELECT t.*, u.email FROM tasks t LEFT JOIN users u ON u.id = t.owner")
    assert statement.tables == ("tasks", "users")
    assert statement.outer_tables == ("users",)
