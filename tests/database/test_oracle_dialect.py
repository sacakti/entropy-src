def test_insert_returns_the_generated_key() -> None:
    statement = translate("INSERT INTO users (name) VALUES (?)", Catalog())
    assert (
        statement.render(("a",))[0]
        == "INSERT INTO users (name) VALUES (:b0) RETURNING id INTO :rid"
    )
    assert translate("INSERT INTO log (message) VALUES (?)", Catalog()).returning is None


def test_replace_becomes_merge_on_the_key() -> None:
    text = sql(
        "INSERT OR REPLACE INTO settings (key, value, updated_at) VALUES (?, ?, ?)", Catalog()
    )
    assert text == (
        "MERGE INTO settings USING (SELECT :b0 AS key, :b1 AS value, :b2 AS updated_at FROM DUAL)"
        " excluded"
        " ON (settings.key = excluded.key)"
        " WHEN MATCHED THEN UPDATE SET value = excluded.value, updated_at = excluded.updated_at"
        " WHEN NOT MATCHED THEN INSERT (key, value, updated_at)"
        " VALUES (excluded.key, excluded.value, excluded.updated_at)"
    )


def test_insert_or_ignore_uses_a_key_it_fills() -> None:
    statement = translate(
        "INSERT OR IGNORE INTO permissions (module_id, name, description)"
        " SELECT id, ?, CASE WHEN ? THEN 'a' ELSE 'b' END FROM modules WHERE name = ?",
        Catalog(),
    )
    assert statement.render(None)[0] == (
        "MERGE INTO permissions USING (SELECT id AS module_id, :b0 AS name,"
        " CASE WHEN :b1 THEN 'a' ELSE 'b' END AS description FROM modules WHERE name = :b2)"
        " excluded"
        " ON (permissions.name = excluded.name)"
        " WHEN NOT MATCHED THEN INSERT (module_id, name, description)"
        " VALUES (excluded.module_id, excluded.name, excluded.description)"
    )
    assert statement.ignore_duplicates
    plain = translate("INSERT OR IGNORE INTO log (message) VALUES (?)", Catalog())
    assert plain.render(None)[0] == "INSERT INTO log (message) VALUES (:b0)"
    assert plain.ignore_duplicates


def test_on_conflict_update_reads_the_existing_row() -> None:
    statement = translate(
        "INSERT INTO task_versions (project_id, version) VALUES (?, 1)"
        " ON CONFLICT (project_id) DO UPDATE SET version = version + ?",
        Catalog(),
    )
    assert statement.render(None)[0] == (
        "MERGE INTO task_versions USING (SELECT :b0 AS project_id, 1 AS version FROM DUAL) excluded"
        " ON (task_versions.project_id = excluded.project_id)"
        " WHEN MATCHED THEN UPDATE SET version = task_versions.version + :b1"
        " WHEN NOT MATCHED THEN INSERT (project_id, version) VALUES (excluded.project_id,"
        " excluded.version)"
    )
    assert statement.assigned == {1}


def test_on_conflict_do_nothing() -> None:
    text = sql("INSERT INTO users (name) VALUES (?) ON CONFLICT(name) DO NOTHING", Catalog())
    assert text.startswith(
        "MERGE INTO users USING (SELECT :b0 AS name FROM DUAL) excluded ON (users.name ="
        " excluded.name)"
    )
    assert "WHEN MATCHED" not in text


