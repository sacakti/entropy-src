def test_parameters_are_named_in_sqlite_order_even_when_moved() -> None:
    statement = translate("SELECT * FROM t WHERE a = ? ORDER BY id LIMIT ? OFFSET ?")
    text, binds = statement.render(("x", 10, 20))
    assert (
        text == "SELECT * FROM t WHERE a = :b0 ORDER BY id OFFSET :b2 ROWS FETCH NEXT :b1 ROWS ONLY"
    )
    assert binds == {"b0": "x", "b1": 10, "b2": 20}


def test_limit_forms() -> None:
    assert sql("SELECT a FROM t LIMIT 5") == "SELECT a FROM t FETCH FIRST 5 ROWS ONLY"
    assert (
        sql("SELECT a FROM t LIMIT 2, 5") == "SELECT a FROM t OFFSET 2 ROWS FETCH NEXT 5 ROWS ONLY"
    )
    assert sql("SELECT a FROM t LIMIT -1 OFFSET ?") == "SELECT a FROM t OFFSET :b0 ROWS"
    assert sql("DELETE FROM t WHERE id NOT IN (SELECT id FROM t ORDER BY id DESC LIMIT ?)") == (
        "DELETE FROM t WHERE id NOT IN (SELECT id FROM t ORDER BY id DESC FETCH FIRST :b0 ROWS"
        " ONLY)"
    )


def test_text_in_literals_is_never_rewritten() -> None:
    assert (
        sql("SELECT 'LIMIT 1 ?' AS x FROM t WHERE b = ?")
        == "SELECT 'LIMIT 1 ?' AS x FROM t WHERE b = :b0"
    )


# ----------------------------------------------------------------------
# Oracle stores '' as NULL
# ----------------------------------------------------------------------


def test_comparing_with_empty_text_is_a_null_test() -> None:
    assert (
        sql("SELECT a FROM t WHERE b = '' AND c <> ''")
        == "SELECT a FROM t WHERE b IS NULL AND c IS NOT NULL"
    )
    statement = translate("SELECT a FROM t WHERE b = ? AND c != ? AND d >= ?")
    text, binds = statement.render(("", "", ""))
    assert text == "SELECT a FROM t WHERE b IS NULL AND c IS NOT NULL AND d >= :b2"
    assert binds == {"b2": ""}
    assert (
        statement.render(("x", "y", "z"))[0]
        == "SELECT a FROM t WHERE b = :b0 AND c != :b1 AND d >= :b2"
    )


def test_assigning_empty_text_stays_an_assignment() -> None:
    statement = translate("UPDATE t SET a = ?, b = '' WHERE c = ?")
    text, binds = statement.render(("", ""))
    assert text == "UPDATE t SET a = :b0, b = '' WHERE c IS NULL"
    assert binds == {"b0": ""}


