"""Entropy's SQLite SQL, translated for Oracle Database 19c; no server is involved here."""

from __future__ import annotations

import pytest

from lib.database.dialect import DialectError
from lib.database.oracle_dialect import BLANK_MARK, translate


class Catalog:
    """Tables as the translator sees them: users(id, name UNIQUE, email), notes(id, body CLOB)."""

    columns_of = {
        "users": ["id", "name", "email"],
        "settings": ["key", "value", "updated_at"],
        "task_versions": ["project_id", "version"],
        "permissions": ["id", "module_id", "name", "description"],
        "notes": ["id", "body"],
        "log": ["message"],
    }
    keys_of = {
        "users": [["id"], ["name"]],
        "settings": [["key"]],
        "task_versions": [["project_id"]],
        "permissions": [["id"], ["name"]],
        "notes": [["id"]],
        "log": [],
    }

    def columns(self, table):
        return self.columns_of.get(table, [])

    def unique_keys(self, table):
        return self.keys_of.get(table, [])

    def conflict_key(self, table):
        keys = self.unique_keys(table)
        return keys[0] if keys else []

    def identity(self, table):
        return "id" if table in ("users", "permissions", "notes") else None

    def clob_columns(self, table):
        return {"body"} if table == "notes" else set()

    def text_type(self, table, column):
        return "CLOB" if (table, column) == ("users", "email") else None


def sql(text, catalog=None, values=None):
    return translate(text, catalog).render(values)[0]


