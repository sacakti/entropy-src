def test_create_table_types_defaults_and_not_null_text() -> None:
    statement = translate(
        "CREATE TABLE IF NOT EXISTS notes ("
        "id INTEGER PRIMARY KEY AUTOINCREMENT, title TEXT NOT NULL DEFAULT '', body TEXT,"
        " level TEXT, size INTEGER NOT NULL DEFAULT 0, ratio REAL, data BLOB, done BOOLEAN"
        " DEFAULT FALSE,"
        " created_at TEXT NOT NULL DEFAULT (datetime('now')),"
        " owner INTEGER REFERENCES users(id) ON DELETE CASCADE)"
    )
    text = statement.render(None)[0]
    assert text == (
        "CREATE TABLE notes (id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,"
        " title VARCHAR2(4000) DEFAULT '', body CLOB, \"LEVEL\" VARCHAR2(4000),"
        ' "SIZE" NUMBER(19) DEFAULT 0 NOT NULL, ratio BINARY_DOUBLE, data BLOB, done NUMBER(19)'
        " DEFAULT 0,"
        " created_at VARCHAR2(4000) DEFAULT (TO_CHAR(SYS_EXTRACT_UTC(SYSTIMESTAMP), 'YYYY-MM-DD"
        " HH24:MI:SS')),"
        " owner NUMBER(19))"
    )
    assert statement.ignore == {955, 1408}
    assert statement.followups == [
        f"COMMENT ON COLUMN notes.title IS '{BLANK_MARK}'",
        f"COMMENT ON COLUMN notes.created_at IS '{BLANK_MARK}'",
    ]


def test_blob_columns_stay_blob() -> None:
    assert "data BLOB" in sql("CREATE TABLE t (k TEXT PRIMARY KEY, data BLOB)")


def test_key_columns_are_sized_to_fit_an_index() -> None:
    text = sql("CREATE TABLE t (a TEXT NOT NULL, b TEXT NOT NULL, c TEXT, UNIQUE(a, b))")
    assert (
        text
        == "CREATE TABLE t (a VARCHAR2(3000), b VARCHAR2(3000), c VARCHAR2(4000), UNIQUE (a, b))"
    )
    assert "name VARCHAR2(4000) UNIQUE" in sql("CREATE TABLE t (name TEXT UNIQUE)")


def test_the_catalog_can_choose_clob_for_long_copied_text() -> None:
    assert "email CLOB" in sql("CREATE TABLE users (email TEXT)", Catalog())


def test_create_table_as_select() -> None:
    assert sql("CREATE TABLE IF NOT EXISTS a_archive AS SELECT * FROM a WHERE 0") == (
        "CREATE TABLE a_archive AS SELECT * FROM a WHERE 1 = 0"
    )


def test_add_column() -> None:
    statement = translate("ALTER TABLE roles ADD COLUMN scope TEXT NOT NULL DEFAULT 'global'")
    assert (
        statement.render(None)[0] == "ALTER TABLE roles ADD (scope VARCHAR2(4000) DEFAULT 'global')"
    )
    assert statement.followups == [f"COMMENT ON COLUMN roles.scope IS '{BLANK_MARK}'"]


def test_indexes() -> None:
    statement = translate("CREATE UNIQUE INDEX IF NOT EXISTS u ON t (name COLLATE NOCASE, level)")
    assert statement.render(None)[0] == 'CREATE UNIQUE INDEX u ON t (LOWER(name), "LEVEL")'
    assert statement.ignore == {955, 1408}
    # LOWER(name) is as long as name: both count towards the index key.
    assert statement.index == ("t", ("name", "level"))
    partial = sql("CREATE UNIQUE INDEX p ON t(n) WHERE n IS NOT NULL")
    assert partial == "CREATE UNIQUE INDEX p ON t (CASE WHEN n IS NOT NULL THEN n END)"


def test_drop() -> None:
    statement = translate("DROP TABLE IF EXISTS old")
    assert statement.render(None)[0] == "DROP TABLE old PURGE"
    assert statement.ignore == {942}
    assert translate("DROP INDEX IF EXISTS i").ignore == {1418}


